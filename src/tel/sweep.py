"""Size x seed sweeps: generate one config per run, train them, summarize.

    uv run python -m tel.sweep configs/sweep/lstm.yaml configs/sweep/edit.yaml \\
        --sizes 1M --seeds 13 14 15 --jobs 3

For every (base config, size, seed) this writes
configs/sweep/generated/<base>_<size>_s<seed>.yaml (model.target_params and
train.seed set, everything else from the base) and trains it into
runs/<same name>/. Runs whose metrics.json exists are skipped, so an
interrupted sweep resumes where it stopped. Jobs run in parallel, splitting
the CPU threads between them.

With --csv, every finished run's metrics are also written as rows (one per run
and split) to a CSV, e.g. bench/results/m3_sweep/accuracy.csv; already
trained runs are skipped, so this only collects.
"""

from __future__ import annotations

import argparse
import copy
import csv
import json
import os
import statistics
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import yaml

GENERATED = Path("configs/sweep/generated")


def parse_size(text: str) -> int:
    """'1M' -> 1_000_000, '500k' -> 500_000, '2000000' -> 2_000_000."""
    t = text.strip().lower()
    mult = {"k": 1_000, "m": 1_000_000}.get(t[-1], 1)
    return int(float(t[:-1] if t[-1] in "km" else t) * mult)


def size_label(n: int) -> str:
    return f"{n / 1e6:g}M" if n >= 1_000_000 else f"{n / 1e3:g}k"


def make_configs(bases: list[Path], sizes: list[int], seeds: list[int]) -> list[Path]:
    GENERATED.mkdir(parents=True, exist_ok=True)
    paths = []
    for base_path in bases:
        base = yaml.safe_load(base_path.read_text(encoding="utf-8"))
        for size in sizes:
            for seed in seeds:
                cfg = copy.deepcopy(base)
                name = f"{base['name']}_{size_label(size)}_s{seed}"
                cfg["name"] = name
                cfg.setdefault("model", {})["target_params"] = size
                cfg.setdefault("train", {})["seed"] = seed
                path = GENERATED / f"{name}.yaml"
                header = f"# Generated by tel.sweep from {base_path} (size {size}, seed {seed}).\n"
                path.write_text(header + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True),
                                encoding="utf-8")
                paths.append(path)
    return paths


def train_one(config: Path, threads: int) -> tuple[str, int]:
    name = config.stem
    run = Path("runs") / name
    if (run / "metrics.json").exists():
        return name, 0
    run.mkdir(parents=True, exist_ok=True)
    env = {**os.environ, "OMP_NUM_THREADS": str(threads), "PYTHONUNBUFFERED": "1"}
    with open(run / "train.log", "w", encoding="utf-8") as log:
        proc = subprocess.run([sys.executable, "-m", "tel.train", str(config)], stdout=log,
                              stderr=subprocess.STDOUT, env=env)
    return name, proc.returncode


CSV_COLUMNS = ["run", "base", "target_params", "params", "seed", "train_file", "split", "n",
               "acc", "acc_noun", "acc_verb", "acc_other", "acc_seen", "acc_unseen",
               "best_epoch", "train_time_s", "git_sha"]
SPLITS = ("dev", "test", "test_unseen")


def collect_rows(configs: list[Path]) -> list[dict]:
    """One row per (finished run, split), from runs/<name>/metrics.json and its config."""
    rows = []
    for config in configs:
        metrics = Path("runs") / config.stem / "metrics.json"
        if not metrics.exists():
            continue
        m = json.loads(metrics.read_text(encoding="utf-8"))
        cfg = yaml.safe_load(config.read_text(encoding="utf-8"))
        base = config.stem.rsplit("_", 2)[0]
        for split in SPLITS:
            r = m[split]
            rows.append({
                "run": m["name"], "base": base, "target_params": cfg["model"]["target_params"],
                "params": m["params"], "seed": m["seed"],
                "train_file": cfg.get("data", {}).get("train_file", "train.tsv"),
                "split": split, "n": r["n"],
                **{k: "" if r.get(k) is None else f"{r[k]:.4f}" for k in CSV_COLUMNS[8:14]},
                "best_epoch": m.get("best_epoch", ""), "train_time_s": m.get("train_time_s", ""),
                "git_sha": m.get("git_sha", "")[:7],
            })
    return rows


def write_csv(rows: list[dict], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=CSV_COLUMNS)
        w.writeheader()
        w.writerows(rows)


def summarize(configs: list[Path]) -> None:
    groups: dict[str, list[dict]] = {}
    for config in configs:
        metrics = Path("runs") / config.stem / "metrics.json"
        if metrics.exists():
            group = config.stem.rsplit("_s", 1)[0]
            groups.setdefault(group, []).append(json.loads(metrics.read_text(encoding="utf-8")))

    def fmt(values: list[float]) -> str:
        mean = statistics.mean(values) * 100
        std = statistics.stdev(values) * 100 if len(values) > 1 else 0.0
        return f"{mean:5.1f} ± {std:3.1f}"

    print(f"\n{'group':26} {'n':>2} {'params':>9} {'dev':>12} {'test':>12} {'test_unseen':>12}")
    for group, ms in groups.items():
        params = statistics.mean(m["params"] for m in ms)
        cols = [fmt([m[s]["acc"] for m in ms]) for s in ("dev", "test", "test_unseen")]
        print(f"{group:26} {len(ms):2} {params:9,.0f} " + " ".join(f"{c:>12}" for c in cols))


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("bases", nargs="+", type=Path, help="base YAML configs")
    ap.add_argument("--sizes", nargs="+", required=True, help="parameter targets, e.g. 500k 1M")
    ap.add_argument("--seeds", nargs="+", type=int, default=[13, 14, 15])
    ap.add_argument("--jobs", type=int, default=3)
    ap.add_argument("--dry-run", action="store_true", help="only write the configs")
    ap.add_argument("--csv", type=Path, help="also write per-run metrics to this CSV")
    args = ap.parse_args()

    configs = make_configs(args.bases, [parse_size(s) for s in args.sizes], args.seeds)
    print(f"{len(configs)} configs in {GENERATED}/")
    if args.dry_run:
        return
    threads = max(1, (os.cpu_count() or 2) // (2 * args.jobs))  # physical cores per job
    failed = []
    with ThreadPoolExecutor(max_workers=args.jobs) as pool:
        for name, code in pool.map(lambda c: train_one(c, threads), configs):
            print(f"{'FAILED' if code else 'done  '} {name}", flush=True)
            if code:
                failed.append(name)
    summarize(configs)
    if args.csv:
        rows = collect_rows(configs)
        write_csv(rows, args.csv)
        print(f"{len(rows)} rows -> {args.csv}")
    if failed:
        sys.exit(f"{len(failed)} run(s) failed; see runs/<name>/train.log: {failed}")


if __name__ == "__main__":
    main()
